"""The engine API surface the desktop app uses (internal tool for the open/closed split).

Walks every module of the closed package ``src/aester_desktop`` and records each ``starstack`` module and name
it uses -- ``from starstack.X import a``, ``from starstack import X`` / ``import starstack.X as Y`` followed by
``Y.attr`` -- with a signature for callables. The result is ``src/starstack/public_api.json``:

* tests/test_open_core_boundary.py checks every listed name still exists with the same signature (open side);
* tests/desktop/test_desktop_boundary.py checks the file equals a fresh scan (closed side), so a new engine name
  used by the GUI must be added here on purpose.

Usage: ``python scripts/split/api_surface.py --write | --check`` (PYTHONPATH=src).
"""
from __future__ import annotations

import ast
import importlib
import inspect
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CLOSED = ROOT / "src" / "aester_desktop"
OPEN = ROOT / "src" / "starstack"
OUTPUT = OPEN / "public_api.json"
RECORD_FILES = ["job.json", "workflow.json", "audit.json"]
_ADDRESS = re.compile(r" at 0x[0-9A-Fa-f]+")


def _is_module(name: str) -> bool:
    return (OPEN / f"{name}.py").is_file()


def used_names(folder: Path = CLOSED) -> dict[str, set[str]]:
    """{open module: names used from it} over every closed module (module-level and function-local code)."""
    used: dict[str, set[str]] = {}
    for path in sorted(folder.rglob("*.py")):
        tree = ast.parse(path.read_text(encoding="utf-8"))
        aliases: dict[str, str] = {}
        for node in ast.walk(tree):
            if isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
                parts = node.module.split(".")
                if parts[0] != "starstack":
                    continue
                if len(parts) == 1:
                    for alias in node.names:
                        if _is_module(alias.name):
                            aliases[alias.asname or alias.name] = alias.name
                            used.setdefault(alias.name, set())
                        else:
                            used.setdefault("__init__", set()).add(alias.name)
                else:
                    module = parts[1]
                    for alias in node.names:
                        used.setdefault(module, set()).add(alias.name)
            elif isinstance(node, ast.Import):
                for alias in node.names:
                    parts = alias.name.split(".")
                    if parts[0] == "starstack" and len(parts) > 1 and alias.asname:
                        aliases[alias.asname] = parts[1]
                        used.setdefault(parts[1], set())
        for node in ast.walk(tree):
            if isinstance(node, ast.Attribute) and isinstance(node.value, ast.Name) and node.value.id in aliases:
                used[aliases[node.value.id]].add(node.attr)
    return used


def _describe(obj) -> str:
    if inspect.isclass(obj):
        return "class"
    if callable(obj):
        try:
            return _ADDRESS.sub("", str(inspect.signature(obj)))
        except (TypeError, ValueError):
            return "callable"
    return "constant:" + type(obj).__name__


def surface(folder: Path = CLOSED) -> dict:
    sys.path.insert(0, str(ROOT / "src"))
    modules = {}
    for module, names in sorted(used_names(folder).items()):
        imported = importlib.import_module("starstack" if module == "__init__" else f"starstack.{module}")
        modules[module] = {name: _describe(getattr(imported, name)) for name in sorted(names)}
    return {"api_version": 1, "note": "The engine names the desktop app uses; "
            "generated by scripts/split/api_surface.py. Changing one of these is an API change for the app.",
            "record_files": RECORD_FILES, "modules": modules}


def render(value: dict) -> str:
    return json.dumps(value, ensure_ascii=False, indent=1, sort_keys=True) + "\n"


def main(argv: list[str]) -> int:
    if argv not in (["--write"], ["--check"]):
        raise SystemExit("usage: api_surface.py --write | --check")
    text = render(surface())
    if argv == ["--write"]:
        OUTPUT.write_bytes(text.encode("utf-8"))
        print(f"wrote {OUTPUT.relative_to(ROOT)}")
        return 0
    current = OUTPUT.read_bytes().decode("utf-8") if OUTPUT.is_file() else ""
    if current != text:
        print("public_api.json is out of date; run scripts/split/api_surface.py --write")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
