"""Bounded rectangle-support queries on a uint64 invalid-pixel integral image.

This module is a conservative geometric primitive only.  It performs no
interpolation and makes no claim about Siril support itself.
"""

import numpy as np

__all__ = ["invalid_integral", "rectangle_support"]


def _validate_validity(validity) -> tuple[int, int]:
    """invalid_integral's input checks (messages unchanged); returns ``(h, w)``."""
    if type(validity) is not np.ndarray:
        raise ValueError("validity must be a numpy ndarray")
    if validity.dtype != np.bool_:
        raise ValueError("validity must have dtype bool")
    if validity.ndim != 2:
        raise ValueError("validity must be 2-D")
    h, w = validity.shape
    if h <= 0 or w <= 0:
        raise ValueError("validity must have positive dimensions")
    return h, w


def invalid_integral(validity: np.ndarray) -> np.ndarray:
    """Return a C-contiguous uint64 integral image of invalid pixels.

    ``validity`` must be an exact 2-D bool ndarray with positive H and W.
    Invalid pixels are ``~validity``.  The result has shape ``(H+1, W+1)``,
    dtype uint64, and a zero top row and left column.  Building costs O(H*W);
    arbitrary input strides are accepted and the input is not mutated.
    """
    h, w = _validate_validity(validity)

    table = np.zeros((h + 1, w + 1), dtype=np.uint64)
    invalid = ~validity
    table[1:, 1:] = np.cumsum(
        np.cumsum(invalid, axis=0, dtype=np.uint64),
        axis=1,
        dtype=np.uint64,
    )
    return table


def rectangle_support(
    integral: np.ndarray,
    points: np.ndarray,
    *,
    before: int = 4,
    after: int = 5,
) -> np.ndarray:
    """Return a bool mask for points whose full rectangular footprint is valid.

    ``integral`` must be a uint64 2-D table from :func:`invalid_integral`.
    ``points`` is an ``(N, 2)`` numeric real finite ndarray, x then y.  For each
    point, the inclusive footprint ``floor(x)-before .. floor(x)+after`` by
    ``floor(y)-before .. floor(y)+after`` must lie entirely inside the source
    image and contain no invalid pixels.  Footprints outside the image, or
    touching any invalid pixel, yield False.  ``before=4, after=5`` tests a
    10x10 source rectangle.  Query cost is O(N) and no N-by-image temporary is
    allocated.  The table border is validated; full-table consistency is
    assumed per the internally-generated-table contract.  Huge nonnegative
    ``before``/``after`` values yield all False.
    """
    # Validate the integral table.
    if type(integral) is not np.ndarray:
        raise ValueError("integral must be a numpy ndarray")
    if integral.dtype != np.uint64:
        raise ValueError("integral must have dtype uint64")
    if integral.ndim != 2:
        raise ValueError("integral must be 2-D")
    if integral.shape[0] < 2 or integral.shape[1] < 2:
        raise ValueError("integral must have both dimensions >= 2")
    # Check only the border; the contract states this table was generated by
    # invalid_integral, so a full O(H*W) rescan per call is not needed.
    if integral[0, :].any() or integral[:, 0].any():
        raise ValueError("integral top row and left column must be zero")
    h = int(integral.shape[0] - 1)
    w = int(integral.shape[1] - 1)

    # Validate points.
    if type(points) is not np.ndarray:
        raise ValueError("points must be a numpy ndarray")
    if points.ndim != 2 or points.shape[1] != 2:
        raise ValueError("points must have shape (N, 2)")
    pdt = points.dtype
    if (
        pdt == np.bool_
        or not np.issubdtype(pdt, np.number)
        or np.issubdtype(pdt, np.complexfloating)
    ):
        raise ValueError("points must have a real numeric dtype")
    if not np.isfinite(points).all():
        raise ValueError("points must contain only finite values")

    # Validate before/after as exact built-in ints.
    if type(before) is not int or type(after) is not int:
        raise ValueError("before and after must be built-in ints")
    if before < 0 or after < 0:
        raise ValueError("before and after must be nonnegative")

    n = points.shape[0]
    result = np.zeros(n, dtype=bool)

    # If one side cannot fit in the source image, the strict footprint is
    # impossible for every point.  This also handles huge ints such as 10**10000
    # without converting them to a fixed-width dtype.
    if before >= w or after >= w or before >= h or after >= h:
        return result

    # In-bounds filter using the original coordinates, before narrowing to
    # integer pixel indices.  For integer before/after:
    #   floor(v) - before >= 0          <=>  v >= before
    #   floor(v) + after <= extent - 1  <=>  v < extent - after
    x = points[:, 0]
    y = points[:, 1]
    x_limit = w - after
    y_limit = h - after
    inside = (x >= before) & (x < x_limit) & (y >= before) & (y < y_limit)
    if not inside.any():
        return result

    # Narrow only points whose entire footprint is already inside the image.
    sub = points[inside]
    floors = np.floor(sub)
    xi = floors[:, 0].astype(np.intp)
    yi = floors[:, 1].astype(np.intp)

    y0 = yi - before
    y1 = yi + after + 1
    x0 = xi - before
    x1 = xi + after + 1

    c00 = integral[y0, x0]
    c01 = integral[y0, x1]
    c10 = integral[y1, x0]
    c11 = integral[y1, x1]

    # Rectangle count = c11 + c00 - c10 - c01.  For a valid monotone integral,
    # c11 - c10 and c01 - c00 are each nonnegative, so this comparison of
    # opposite corner sums is exact and avoids uint64 underflow/overflow.
    unsupported = (c11 - c10) != (c01 - c00)
    result[inside] = ~unsupported
    return result
